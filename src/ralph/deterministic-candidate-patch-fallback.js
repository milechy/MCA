const fs = require('node:fs');
const path = require('node:path');

const PATCH_SOURCE = 'deterministic_fallback';
const ELIGIBLE_FAILURE_REASONS = new Set([
  'provider_rate_limited',
  'candidate_patch_missing',
  'agent_output_contract_violation'
]);
const DEFAULT_ALLOWED_PREFIXES = [
  'README',
  'docs/',
  'tests/',
  '.github/'
];
const DEFAULT_ALLOWED_EXTENSIONS = new Set([
  '.md',
  '.txt',
  '.json',
  '.yml',
  '.yaml'
]);
const MAX_PATCH_BYTES = 16 * 1024;
const MAX_TASK_CHARS = 2000;

function oneLine(value, maxLength = 240) {
  const normalized = String(value || '')
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (normalized.length <= maxLength) return normalized;
  return `${normalized.slice(0, Math.max(0, maxLength - 1))}…`;
}

function safeRequestedPath(value) {
  const normalized = String(value || '').replace(/\\/g, '/').replace(/^\.\//, '').trim();
  if (!normalized || normalized.startsWith('/') || normalized.includes('..')) return null;
  if (/\0/.test(normalized)) return null;
  return normalized;
}

function requestedPaths(story = {}, requested_paths = null) {
  const source = Array.isArray(requested_paths) ? requested_paths : story.requested_paths;
  if (!Array.isArray(source)) return [];
  return Array.from(new Set(source.map(safeRequestedPath).filter(Boolean))).slice(0, 20);
}

function riskIsLow(story = {}, risk = null) {
  const effective = risk || story.risk || story.last_risk || story.last_ultraplan?.risk || null;
  if (!effective) return true;
  if (typeof effective.score === 'number') return effective.score < 5;
  const category = String(effective.category || effective.label || '').toLowerCase();
  return !category || category.includes('low') || category.includes('risk_0') || category.includes('risk_1');
}

function pathIsPolicyAllowed(filePath, { allow_runtime_code = false, allowed_prefixes = DEFAULT_ALLOWED_PREFIXES, allowed_extensions = DEFAULT_ALLOWED_EXTENSIONS } = {}) {
  const safePath = safeRequestedPath(filePath);
  if (!safePath) return false;
  if (allow_runtime_code) return true;
  if (allowed_prefixes.some((prefix) => safePath === prefix || safePath.startsWith(prefix))) return true;
  return allowed_extensions.has(path.extname(safePath));
}

function repoFileExists(rootDir, filePath) {
  const safePath = safeRequestedPath(filePath);
  if (!safePath) return true;
  const absolute = path.resolve(rootDir, safePath);
  if (!absolute.startsWith(path.resolve(rootDir))) return true;
  try { return fs.statSync(absolute).isFile(); } catch { return false; }
}

function eligibleForDeterministicFallback({ story = {}, failure_reason, requested_paths = null, risk = null, allow_runtime_code = false, rootDir = process.cwd() } = {}) {
  if (!ELIGIBLE_FAILURE_REASONS.has(String(failure_reason || ''))) {
    return { ok: false, reason: 'fallback_failure_reason_not_allowed' };
  }
  if (!riskIsLow(story, risk)) {
    return { ok: false, reason: 'fallback_risk_not_low' };
  }
  const paths = requestedPaths(story, requested_paths);
  if (paths.length !== 1) {
    return { ok: false, reason: 'fallback_requires_exactly_one_requested_path', requested_paths: paths };
  }
  const target = paths[0];
  if (!pathIsPolicyAllowed(target, { allow_runtime_code })) {
    return { ok: false, reason: 'fallback_requested_path_not_policy_allowed', path: target };
  }
  if (repoFileExists(rootDir, target)) {
    return { ok: false, reason: 'fallback_existing_file_requires_provider_context', path: target };
  }
  return { ok: true, reason: null, requested_paths: paths, path: target };
}

function lineForPatch(line) {
  return `+${String(line || '').replace(/\r/g, '')}`;
}

function deterministicFileContent({ story = {}, task = '', target }) {
  const title = oneLine(story.title || story.requirement || task || 'Ralph deterministic fallback candidate', 160);
  const requirement = String(story.requirement || task || '').slice(0, MAX_TASK_CHARS).trim();
  const ext = path.extname(target);
  if (ext === '.json') {
    return `${JSON.stringify({ generated_by: PATCH_SOURCE, title, requirement }, null, 2)}\n`;
  }
  if (ext === '.yml' || ext === '.yaml') {
    return [
      'generated_by: deterministic_fallback',
      `title: ${JSON.stringify(title)}`,
      `requirement: ${JSON.stringify(oneLine(requirement, 500))}`,
      ''
    ].join('\n');
  }
  return [
    `# ${title}`,
    '',
    'This candidate patch was generated by Ralph deterministic fallback because the external provider did not produce a candidate patch.',
    '',
    'It is intentionally limited to the requested path and still requires normal diff approval before apply.',
    '',
    requirement ? `Requirement: ${oneLine(requirement, 1000)}` : null,
    ''
  ].filter((line) => line !== null).join('\n');
}

function unifiedNewFilePatch(filePath, content) {
  const lines = String(content || '').split('\n');
  const body = lines.map(lineForPatch).join('\n');
  return [
    `diff --git a/${filePath} b/${filePath}`,
    'new file mode 100644',
    'index 0000000..0000000',
    '--- /dev/null',
    `+++ b/${filePath}`,
    `@@ -0,0 +1,${Math.max(1, lines.length)} @@`,
    body,
    ''
  ].join('\n');
}

function writeDeterministicCandidatePatch({ rootDir = process.cwd(), story = {}, failure_reason, requested_paths = null, sandbox_root, candidate_patch_path = null, task = '', approval_id = null, job_id = null, now = () => new Date(), allow_runtime_code = false } = {}) {
  const eligibility = eligibleForDeterministicFallback({ rootDir, story, failure_reason, requested_paths, allow_runtime_code });
  const started = now();
  const finished = now();
  const base = {
    stage: 'deterministic_candidate_patch_fallback',
    approval_id,
    job_id,
    patch_source: PATCH_SOURCE,
    provider_failure_reason: failure_reason || null,
    started_at: started.toISOString(),
    finished_at: finished.toISOString(),
    duration_ms: Math.max(0, finished.getTime() - started.getTime()),
    execution_connected: false,
    commands_executed: [],
    repository_files_modified: [],
    apply_allowed: false,
    commit_allowed: false,
    push_allowed: false,
    pr_allowed: false,
    merge_allowed: false,
    deploy_allowed: false,
    migration_allowed: false
  };
  if (!eligibility.ok) {
    return {
      ...base,
      ok: false,
      reason: eligibility.reason,
      candidate_patch_path: null,
      files_modified: [],
      fallback_eligibility: eligibility,
      next_action: 'retry_or_escalate_provider_failure'
    };
  }

  const safeSandbox = safeRequestedPath(sandbox_root || '');
  if (!safeSandbox || !safeSandbox.startsWith('.ralph/tmp/')) {
    return {
      ...base,
      ok: false,
      reason: 'fallback_sandbox_root_not_allowed',
      candidate_patch_path: null,
      files_modified: [],
      fallback_eligibility: eligibility,
      next_action: 'fix_fallback_sandbox_root'
    };
  }
  const patchPath = candidate_patch_path || `${safeSandbox}/candidate.patch`;
  const absolutePatchPath = path.resolve(rootDir, patchPath);
  const expectedPrefix = path.resolve(rootDir, '.ralph', 'tmp');
  if (!absolutePatchPath.startsWith(expectedPrefix)) {
    return {
      ...base,
      ok: false,
      reason: 'fallback_candidate_patch_path_not_allowed',
      candidate_patch_path: null,
      files_modified: [],
      fallback_eligibility: eligibility,
      next_action: 'fix_fallback_candidate_patch_path'
    };
  }

  const content = deterministicFileContent({ story, task, target: eligibility.path });
  const patchText = unifiedNewFilePatch(eligibility.path, content);
  if (Buffer.byteLength(patchText, 'utf8') > MAX_PATCH_BYTES) {
    return {
      ...base,
      ok: false,
      reason: 'fallback_patch_too_large',
      candidate_patch_path: null,
      files_modified: [],
      fallback_eligibility: eligibility,
      next_action: 'retry_or_escalate_provider_failure'
    };
  }

  fs.mkdirSync(path.dirname(absolutePatchPath), { recursive: true });
  fs.writeFileSync(absolutePatchPath, patchText, 'utf8');
  return {
    ...base,
    ok: true,
    reason: null,
    candidate_patch_path: patchPath,
    sandbox_root: safeSandbox,
    files_modified: [patchPath],
    fallback_eligibility: eligibility,
    patch_preview: {
      ok: true,
      requires_approval: true,
      apply_allowed: false,
      patch_source: PATCH_SOURCE,
      files_touched: [eligibility.path],
      blocked_paths: [],
      diff_bytes: Buffer.byteLength(patchText, 'utf8')
    },
    next_action: 'preview_candidate_patch_before_apply'
  };
}

module.exports = {
  PATCH_SOURCE,
  ELIGIBLE_FAILURE_REASONS,
  safeRequestedPath,
  requestedPaths,
  riskIsLow,
  pathIsPolicyAllowed,
  eligibleForDeterministicFallback,
  deterministicFileContent,
  unifiedNewFilePatch,
  writeDeterministicCandidatePatch
};
